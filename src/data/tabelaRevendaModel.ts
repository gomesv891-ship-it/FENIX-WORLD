/**
 * REGRA EXIGIDA: "Atualizar preços vinculados"
 * Busca novamente os preços atuais dos produtos vinculados ao CRM.
 * Se o preço foi alterado manualmente nesta tabela, mantém o preço manual.
 * NUNCA altera o preço principal do produto no CRM.
 */
export function atualizarPrecosVinculados(
  produtos: TabelaLinhaProduto[],
  tipoTabela: 'Revenda' | 'Construtora' | 'Distribuidor' | 'Geral' = 'Revenda'
): { produtosAtualizados: TabelaLinhaProduto[]; totalAtualizados: number } {
  const officialCrmProducts = getOfficialProducts();
  let count = 0;

  const atualizados = produtos.map((p) => {
    // Se o preço foi marcado como manual pelo usuário, preserva
    if (p.isPrecoManual) return p;

    // Procura por correspondência direta de CRM Product ID ou por nome
    const crmItem = officialCrmProducts.find((crm) => {
      if (p.crmProductId && crm.id === p.crmProductId) return true;
      if (p.crmProductName && crm.name.toLowerCase().includes(p.crmProductName.toLowerCase()))
        return true;
      const cleanDesc = p.descricao.toLowerCase();
      return (
        cleanDesc.includes(crm.name.toLowerCase()) ||
        crm.name.toLowerCase().includes(cleanDesc.slice(0, 20))
      );
    });

    if (crmItem) {
      let novoPreco = p.preco;
      if (tipoTabela === 'Construtora' && crmItem.priceConstrutora) {
        novoPreco = crmItem.priceConstrutora;
      } else if (tipoTabela === 'Revenda' && crmItem.priceRevenda) {
        novoPreco = crmItem.priceRevenda;
      } else if (tipoTabela === 'Distribuidor' && crmItem.priceDistribuidor) {
        novoPreco = crmItem.priceDistribuidor;
      } else if (crmItem.price) {
        novoPreco = crmItem.price;
      }

      if (novoPreco !== p.preco) {
        count++;
        return {
          ...p,
          preco: novoPreco,
          crmProductId: crmItem.id,
          crmProductName: crmItem.name,
        };
      }
    }

    return p;
  });

  return { produtosAtualizados: atualizados, totalAtualizados: count };
}
